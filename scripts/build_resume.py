"""Generate resume/main.tex from _data/resume.yml, the single source of the resume.

The web page (resume.md) renders the same data through Jekyll. Notes in the data are for the author
and stay out of the LaTeX, so the PDF never carries them.

The email is written in an anti-scraping form ("name at gmail dot com") and shown as plain text. The phone
number is never kept in the repository or in the published PDF; for a private copy to send out, set
RESUME_PHONE in your own shell and build to a file that is not committed:
  RESUME_PHONE="..." python scripts/build_resume.py --out resume/private.tex

Usage:
  python scripts/build_resume.py [--out resume/main.tex]
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "_data" / "resume.yml"
LATEX_SPECIALS = {"%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "$": r"\$"}


def esc(text: str) -> str:
    return "".join(LATEX_SPECIALS.get(c, c) for c in str(text)).replace("–", "--")


def comment(text: str) -> str:
    return " ".join(str(text).split())


def render_item(item: dict) -> list[str]:
    sub = esc(item.get("sub", "")).replace(" · ", "|")
    if sub and item.get("plain_sub"):
        sub = rf"\textnormal{{{sub}}}"
    lines = ["\\ResumeItem", f"{{{esc(item['title'])}}}"]
    if item.get("note"):
        lines[-1] += f" % {comment(item['note'])}"
    lines += [f"[{sub}]", f"[{esc(item.get('date', ''))}]"]
    points = item.get("points") or []
    if points:
        lines += ["\\begin{itemize}"]
        for p in points:
            label = rf"\textbf{{{esc(p['label'])}}}：" if p.get("label") else ""
            lines.append(rf"\item {label}{esc(p['text'])}")
            if p.get("note"):
                lines.append(f"% {comment(p['note'])}")
        lines += ["\\end{itemize}"]
    return lines + [""]


def contacts(data: dict) -> str | None:
    phone = os.environ.get("RESUME_PHONE", "").strip()
    parts = ([esc(phone)] if phone else []) + ([esc(data["email"])] if data.get("email") else [])
    return "，".join(parts) if parts else None


def render(data: dict) -> str:
    out = ["% !TeX TS-program = xelatex", "% Generated by scripts/build_resume.py from _data/resume.yml; edit that file instead.", "",
           r"\documentclass{resume}", rf"\ResumeName{{{esc(data['name'])}}}", "", r"\begin{document}", ""]
    contact = contacts(data)
    if contact:
        out += [rf"\ResumeContacts{{{contact}}}", ""]
    out += [r"\ResumeTitle", ""]
    for section in data["sections"]:
        head = rf"\section{{{esc(section['title'])}}}"
        if section.get("note"):
            head += f" % {comment(section['note'])}"
        out += [head, ""]
        for item in section["items"]:
            out += render_item(item)
    if data.get("footer_note"):
        out += [f"% {comment(data['footer_note'])}"]
    out += [r"\end{document}", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=ROOT / "resume" / "main.tex")
    args = parser.parse_args()
    data = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    args.out.write_text(render(data), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}" + (" (includes RESUME_PHONE)" if os.environ.get("RESUME_PHONE") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
