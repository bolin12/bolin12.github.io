"""Generate the LaTeX resumes from the YAML data, which is the single source of the resume.

  zh  _data/resume.yml     -> resume/main.tex     uses resume/resume.cls (XeLaTeX)
  en  _data/resume_en.yml  -> resume/main_en.tex  self-contained, Jake's Resume layout (pdfLaTeX)

The web pages render the same data through Jekyll. Notes in the data are for the author and stay out
of the LaTeX, so the PDF never carries them.

The email is written in an anti-scraping form ("name at gmail dot com") and shown as plain text. The phone
number is never kept in the repository or in the published files; for a private copy to send out, set
RESUME_PHONE in your own shell and build to a file that is not committed:
  RESUME_PHONE="..." python scripts/build_resume.py --out resume/private.tex

Usage:
  python scripts/build_resume.py [--lang zh|en] [--out PATH]
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {"zh": ROOT / "_data" / "resume.yml", "en": ROOT / "_data" / "resume_en.yml"}
TARGETS = {"zh": ROOT / "resume" / "main.tex", "en": ROOT / "resume" / "main_en.tex"}
LATEX_SPECIALS = {"%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_", "$": r"\$"}

# Layout by Jake Gutierrez (https://github.com/jakegut/resume, MIT license), trimmed to what the data needs.
JAKE_PREAMBLE = r"""\documentclass[a4paper,11pt]{article}
\usepackage{latexsym}
\usepackage[empty]{fullpage}
\usepackage{titlesec}
\usepackage{marvosym}
\usepackage[usenames,dvipsnames]{color}
\usepackage{verbatim}
\usepackage{enumitem}
\usepackage[hidelinks]{hyperref}
\usepackage{fancyhdr}
\usepackage[english]{babel}
\usepackage{tabularx}
\input{glyphtounicode}

\pagestyle{fancy}
\fancyhf{}
\fancyfoot{}
\renewcommand{\headrulewidth}{0pt}
\renewcommand{\footrulewidth}{0pt}

\addtolength{\oddsidemargin}{-0.5in}
\addtolength{\evensidemargin}{-0.5in}
\addtolength{\textwidth}{1in}
\addtolength{\topmargin}{-.5in}
\addtolength{\textheight}{1.0in}

\urlstyle{same}
\raggedbottom
\raggedright
\setlength{\tabcolsep}{0in}

\titleformat{\section}{\vspace{-4pt}\scshape\raggedright\large}{}{0em}{}[\color{black}\titlerule \vspace{-5pt}]
\pdfgentounicode=1

\newcommand{\resumeItem}[1]{\item\small{#1 \vspace{-2pt}}}
\newcommand{\resumeSubheading}[4]{
  \vspace{-2pt}\item
    \begin{tabular*}{0.97\textwidth}[t]{l@{\extracolsep{\fill}}r}
      \textbf{#1} & #2 \\
      \textit{\small#3} & \textit{\small #4} \\
    \end{tabular*}\vspace{-7pt}
}
\newcommand{\resumeProjectHeading}[2]{
    \item
    \begin{tabular*}{0.97\textwidth}{l@{\extracolsep{\fill}}r}
      \small#1 & #2 \\
    \end{tabular*}\vspace{-7pt}
}
\newcommand{\resumeSubHeadingListStart}{\begin{itemize}[leftmargin=0.15in, label={}]}
\newcommand{\resumeSubHeadingListEnd}{\end{itemize}}
\newcommand{\resumeItemListStart}{\begin{itemize}}
\newcommand{\resumeItemListEnd}{\end{itemize}\vspace{-5pt}}
"""


def esc(text: str) -> str:
    return "".join(LATEX_SPECIALS.get(c, c) for c in str(text)).replace("–", "--")


def comment(text: str) -> str:
    return " ".join(str(text).split())


def contacts(data: dict, separator: str) -> str | None:
    """The obfuscated email, plus a phone number only when RESUME_PHONE is set (local, private builds)."""
    phone = os.environ.get("RESUME_PHONE", "").strip()
    parts = ([esc(phone)] if phone else []) + ([esc(data["email"])] if data.get("email") else [])
    return separator.join(parts) if parts else None


# --- Chinese: resume.cls -------------------------------------------------------------------------

def render_item_zh(item: dict) -> list[str]:
    sub = esc(item.get("sub", "")).replace(" · ", "|")
    if sub and item.get("plain_sub"):
        sub = rf"\textnormal{{{sub}}}"
    lines = ["\\ResumeItem", f"{{{esc(item['title'])}}}"]
    if item.get("note"):
        lines[-1] += f" % {comment(item['note'])}"
    lines += [f"[{sub}]", f"[{esc(item.get('date', ''))}]"]
    points = item.get("points") or []
    if points:
        lines += ["\\begin{itemize}"]
        for p in points:
            label = rf"\textbf{{{esc(p['label'])}}}：" if p.get("label") else ""
            lines.append(rf"\item {label}{esc(p['text'])}")
            if p.get("note"):
                lines.append(f"% {comment(p['note'])}")
        lines += ["\\end{itemize}"]
    return lines + [""]


def render_zh(data: dict) -> str:
    out = ["% !TeX TS-program = xelatex", "% Generated by scripts/build_resume.py from _data/resume.yml; edit that file instead.", "",
           r"\documentclass{resume}", rf"\ResumeName{{{esc(data['name'])}}}", "", r"\begin{document}", ""]
    contact = contacts(data, "，")
    if contact:
        out += [rf"\ResumeContacts{{{contact}}}", ""]
    out += [r"\ResumeTitle", ""]
    for section in data["sections"]:
        head = rf"\section{{{esc(section['title'])}}}"
        if section.get("note"):
            head += f" % {comment(section['note'])}"
        out += [head, ""]
        for item in section["items"]:
            out += render_item_zh(item)
    if data.get("footer_note"):
        out += [f"% {comment(data['footer_note'])}"]
    out += [r"\end{document}", ""]
    return "\n".join(out)


# --- English: Jake's Resume layout ---------------------------------------------------------------

def render_item_en(item: dict) -> list[str]:
    date = esc(item.get("date", ""))
    if item.get("sub"):
        lines = ["    \\resumeSubheading", f"      {{{esc(item['title'])}}}{{{date}}}", f"      {{{esc(item['sub'])}}}{{}}"]
    else:
        lines = [f"    \\resumeProjectHeading", f"      {{\\textbf{{{esc(item['title'])}}}}}{{{date}}}"]
    points = item.get("points") or []
    if points:
        lines.append("      \\resumeItemListStart")
        for p in points:
            label = rf"\textbf{{{esc(p['label'])}}}: " if p.get("label") else ""
            lines.append(rf"        \resumeItem{{{label}{esc(p['text'])}}}")
        lines.append("      \\resumeItemListEnd")
    return lines


def render_en(data: dict) -> str:
    out = ["% Generated by scripts/build_resume.py from _data/resume_en.yml; edit that file instead.",
           "% Layout: Jake's Resume (MIT license). Compile with pdfLaTeX.", JAKE_PREAMBLE, r"\begin{document}", "",
           r"\begin{center}", rf"    \textbf{{\Huge \scshape {esc(data['name'])}}} \\ \vspace{{1pt}}"]
    contact = contacts(data, r" $|$ ")
    if contact:
        out.append(rf"    \small {contact}")
    out += [r"\end{center}", ""]
    for section in data["sections"]:
        out += [rf"\section{{{esc(section['title'])}}}", r"  \resumeSubHeadingListStart"]
        for item in section["items"]:
            out += render_item_en(item)
        out += [r"  \resumeSubHeadingListEnd", ""]
    out += [r"\end{document}", ""]
    return "\n".join(out)


RENDERERS = {"zh": render_zh, "en": render_en}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lang", choices=sorted(RENDERERS), default="zh")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    out = args.out or TARGETS[args.lang]
    data = yaml.safe_load(SOURCES[args.lang].read_text(encoding="utf-8"))
    out.write_text(RENDERERS[args.lang](data), encoding="utf-8", newline="\n")
    print(f"wrote {out}" + (" (includes RESUME_PHONE)" if os.environ.get("RESUME_PHONE") else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
